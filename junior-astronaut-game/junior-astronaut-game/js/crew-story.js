function pickFrom(key,arr){
  G.said=G.said||{};
  let u=G.said[key]||(G.said[key]=[]);
  let idx=arr.map((_,i)=>i).filter(i=>!u.includes(i));
  if(!idx.length){u.length=0;idx=arr.map((_,i)=>i);}
  const i=idx[Math.floor(rnd()*idx.length)];u.push(i);return arr[i];
}
function storyLine(t){
  const per=t<630?'am':t<870?'mid':t<1110?'pm':'eve';
  const night=G.phase==='night';
  const pace=(G.day-1+ (t-DAY_START)/(DAY_END-DAY_START))/G.days;
  const r=G.research/G.target;
  const cond=[];
  if(G.power<35)cond.push('lowpower');
  if(G.food<35)cond.push('lowfood');
  if(G.health<45)cond.push('lowhealth');
  if(pace>0.15&&r<pace*0.75)cond.push('behind');
  if(pace>0.15&&r>pace*1.2)cond.push('ahead');
  if(cond.length&&rnd()<0.5){const k=cond[Math.floor(rnd()*cond.length)];return pickFrom(k,STORY[k]);}
  if(night&&rnd()<0.45)return pickFrom('night',STORY.night);
  return pickFrom(per,STORY[per]);
}
